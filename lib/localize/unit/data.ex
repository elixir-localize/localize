defmodule Localize.Unit.Data do
  @moduledoc """
  Compile-time extraction of CLDR unit data from a pre-built ETF file.

  This module loads unit data from `priv/unit/unit_data.etf`, which is
  generated by `scripts/extract_unit_data.exs` from the CLDR supplemental
  units XML and validity XML files. Run that script whenever the CLDR
  data is updated.

  """

  # alias Localize.Unit.Data.Expression

  # Inlining the `Application.app_dir/2` call at each compile-time use
  # site avoids leaving a `@etf_path` module attribute that a future
  # maintainer could accidentally reference at runtime — which would
  # crash on any host that differs from the build host. Issue #28.
  @external_resource Application.app_dir(
                       :localize,
                       "priv/localize/supplemental_data/unit_data.etf"
                     )

  @data :localize
        |> Application.app_dir("priv/localize/supplemental_data/unit_data.etf")
        |> File.read!()
        |> :erlang.binary_to_term()

  @prefix_components @data.prefix_components
  @suffix_components @data.suffix_components
  @power_components @data.power_components
  @si_prefix_data @data.si_prefix_data
  @si_prefix_names @data.si_prefix_names
  @si_prefix_multipliers @data.si_prefix_multipliers
  @base_units @data.base_units
  @conversions @data.conversions
  # @unit_quantities @data.unit_quantities
  @simple_base_units @data.simple_base_units
  @base_unit_order @data.base_unit_order
  @base_unit_to_quantity @data.base_unit_to_quantity
  @unit_preferences @data.unit_preferences
  @unit_constants @data.unit_constants
  @conversion_factors @data.conversion_factors
  @valid_unit_identifiers @data.valid_unit_identifiers
  @deprecated_unit_identifiers @data.deprecated_unit_identifiers
  @categories @data.categories

  # ── Public API ──────────────────────────────────────────────────────

  @doc """
  Returns the list of unit ID prefix components.

  ### Returns

  * A list of strings such as `["arc", "british", "dessert", ...]`.

  ### Examples

      iex> "arc" in Localize.Unit.Data.prefix_components()
      true

  """
  @spec prefix_components() :: [String.t()]
  def prefix_components, do: @prefix_components

  @doc """
  Returns the list of unit ID suffix components.

  ### Returns

  * A list of strings such as `["force", "imperial", ...]`.

  ### Examples

      iex> "force" in Localize.Unit.Data.suffix_components()
      true

  """
  @spec suffix_components() :: [String.t()]
  def suffix_components, do: @suffix_components

  @doc """
  Returns the list of power components.

  ### Returns

  * A list of strings such as `["square", "cubic", "pow2", ...]`.

  ### Examples

      iex> "square" in Localize.Unit.Data.power_components()
      true

  """
  @spec power_components() :: [String.t()]
  def power_components, do: @power_components

  @doc """
  Returns the list of SI prefix names.

  ### Returns

  * A list of strings such as `["kilo", "milli", "mega", ...]`.

  ### Examples

      iex> "kilo" in Localize.Unit.Data.si_prefix_names()
      true

  """
  @spec si_prefix_names() :: [String.t()]
  def si_prefix_names, do: @si_prefix_names

  # Pre-built `string => atom` map for SI prefix names. Used by the
  # unit parser to convert a parsed prefix string to its atom form
  # without calling `String.to_atom/1` at runtime — the prefix set is
  # finite and known at compile time, so atomising it once here means
  # parser input never grows the atom table.
  @si_prefix_atom_map Map.new(@si_prefix_names, fn name -> {name, String.to_atom(name)} end)

  @doc """
  Returns the atom form of a parsed SI prefix string, or `nil` if
  the string is not a known SI prefix.

  ### Arguments

  * `name` is an SI prefix string such as `"kilo"`.

  ### Returns

  * The prefix as an atom, or `nil` if `name` is not a known SI prefix.

  ### Examples

      iex> Localize.Unit.Data.si_prefix_atom("kilo")
      :kilo

      iex> Localize.Unit.Data.si_prefix_atom("bogus")
      nil

  """
  @spec si_prefix_atom(String.t()) :: atom() | nil
  def si_prefix_atom(name) when is_binary(name), do: Map.get(@si_prefix_atom_map, name)

  @doc """
  Returns detailed SI prefix data including symbols and powers.

  ### Returns

  * A list of maps with keys `:type`, `:symbol`, `:power10`, and `:power2`.

  ### Examples

      iex> kilo = Enum.find(Localize.Unit.Data.si_prefix_data(), &(&1.type == "kilo"))
      iex> {kilo.symbol, kilo.power10}
      {"k", "3"}

  """
  @spec si_prefix_data() :: [
          %{type: String.t(), symbol: String.t(), power10: String.t(), power2: String.t()},
          ...
        ]
  def si_prefix_data, do: @si_prefix_data

  @doc """
  Returns the list of known base unit names from CLDR conversion data.

  ### Returns

  * A list of strings such as `["meter", "kilogram", "second", ...]`.

  ### Examples

      iex> "meter" in Localize.Unit.Data.base_units()
      true

  """
  @spec base_units() :: [String.t()]
  def base_units, do: @base_units

  @doc """
  Returns all valid CLDR unit identifiers with regular status.

  ### Returns

  * A list of strings such as `["length-kilometer", "mass-kilogram", ...]`.

  ### Examples

      iex> "length-kilometer" in Localize.Unit.Data.valid_unit_identifiers()
      true

  """
  @spec valid_unit_identifiers() :: [String.t()]
  def valid_unit_identifiers, do: @valid_unit_identifiers

  @doc """
  Returns all deprecated CLDR unit identifiers.

  ### Returns

  * A list of strings.

  ### Examples

      iex> "acceleration-meter-per-second-squared" in Localize.Unit.Data.deprecated_unit_identifiers()
      true

  """
  @spec deprecated_unit_identifiers() :: [String.t()]
  def deprecated_unit_identifiers, do: @deprecated_unit_identifiers

  @doc """
  Returns the list of known unit categories.

  ### Returns

  * A list of strings such as `["acceleration", "angle", "area", ...]`.

  ### Examples

      iex> "length" in Localize.Unit.Data.categories()
      true

  """
  @spec categories() :: [String.t()]
  def categories, do: @categories

  @doc """
  Returns a map from source unit name to its CLDR base unit string.

  ### Returns

  * A map such as `%{"foot" => "meter", "newton" => "kilogram-meter-per-square-second", ...}`.

  ### Examples

      iex> Localize.Unit.Data.conversions()["foot"]
      "meter"

  """
  @spec conversions() :: %{String.t() => String.t()}
  def conversions, do: @conversions

  @doc """
  Returns the list of fundamental (simple) base units.

  These are the units with `status='simple'` in the CLDR `unitQuantities`
  data and form the atoms of the dimensional decomposition system.

  ### Returns

  * A list of strings such as `["candela", "kilogram", "meter", "second", ...]`.

  ### Examples

      iex> "kilogram" in Localize.Unit.Data.simple_base_units()
      true

  """
  @spec simple_base_units() :: [String.t()]
  def simple_base_units, do: @simple_base_units

  @doc """
  Returns the canonical ordering of base units from `unitQuantities`.

  This ordering is used to reconstruct canonical base unit strings.

  ### Returns

  * A list of base unit strings in canonical order.

  ### Examples

      iex> hd(Localize.Unit.Data.base_unit_order())
      "candela"

      iex> "meter" in Localize.Unit.Data.base_unit_order()
      true

  """
  @spec base_unit_order() :: [String.t()]
  def base_unit_order, do: @base_unit_order

  @doc """
  Returns the resolved unit constants as a map of name to float value.

  ### Returns

  * A map such as `%{"ft_to_m" => 0.3048, "lb_to_kg" => 0.45359237, ...}`.

  ### Examples

      iex> Localize.Unit.Data.unit_constants()["ft_to_m"]
      0.3048

  """
  @spec unit_constants() :: %{String.t() => float()}
  def unit_constants, do: @unit_constants

  @doc """
  Returns the conversion factor and offset for each source unit.

  The conversion from source to base unit is: `base_value = value * factor + offset`.

  ### Returns

  * A map such as `%{"foot" => %{factor: 0.3048, offset: 0.0}, ...}`.

  ### Examples

      iex> Localize.Unit.Data.conversion_factors()["foot"].factor
      0.3048

  """
  @spec conversion_factors() :: %{String.t() => %{factor: float() | :special, offset: float()}}
  def conversion_factors, do: @conversion_factors

  @doc """
  Returns SI prefix multipliers as a map of prefix name to numeric multiplier.

  ### Returns

  * A map such as `%{"kilo" => 1000.0, "milli" => 0.001, ...}`.

  ### Examples

      iex> Localize.Unit.Data.si_prefix_multipliers()["kilo"]
      1000.0

  """
  @spec si_prefix_multipliers() :: %{String.t() => float()}
  def si_prefix_multipliers, do: @si_prefix_multipliers

  @doc """
  Returns a map from base unit string to its CLDR quantity name.

  ### Returns

  * A map such as `%{"meter" => "length", "kilogram" => "mass", ...}`.

  ### Examples

      iex> Localize.Unit.Data.base_unit_to_quantity()["meter"]
      "length"

  """
  @spec base_unit_to_quantity() :: %{String.t() => String.t()}
  def base_unit_to_quantity, do: @base_unit_to_quantity

  @doc """
  Returns the CLDR unit preference data.

  Each entry specifies preferred units for a category/usage/region
  combination.

  ### Returns

  * A list of maps with keys `:category`, `:usage`, and `:preferences`.

  ### Examples

      iex> [entry | _] = Localize.Unit.Data.unit_preferences()
      iex> Map.keys(entry) |> Enum.sort()
      [:category, :preferences, :usage]

  """
  @spec unit_preferences() :: [
          %{category: String.t(), usage: String.t(), preferences: [map(), ...]},
          ...
        ]
  def unit_preferences, do: @unit_preferences

  # Raw lookups against the compile-time data. The runtime overlay
  # (custom registry first, then compile-time data) lives in
  # `Localize.Unit.Data.Overlay` so this module remains a leaf
  # without runtime back-edges into the broader cycle.

  @doc false
  @spec conversion_factor_raw(String.t()) ::
          %{factor: number() | :special, offset: number()} | nil
  def conversion_factor_raw(unit_name), do: Map.get(@conversion_factors, unit_name)

  @doc false
  @spec conversion_raw(String.t()) :: String.t() | nil
  def conversion_raw(unit_name), do: Map.get(@conversions, unit_name)
end

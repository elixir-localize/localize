defmodule Mix.Tasks.Localize.GenUnicodeCategories do
  @shortdoc "Generates the Unicode category table the number lexer reads"
  @moduledoc """
  Generates `Localize.Number.Lexer.Categories`, the Unicode general
  categories `Localize.Number.Lexer` classes characters by, from the
  `unicode` library.

  The lexer settles most characters with its lexicon: digits, signs
  and separators. What is left it classes by Unicode's general
  category: a format character (`Cf`), a digit of another number
  system (`Nd`), a punctuation mark (`Po` or `Pf`) or a space (`Zs`).
  Those categories change with each Unicode release, so the table is
  generated from the `unicode` library, which tracks them, and checked
  in. Run this task when that library updates:

      mix localize.gen_unicode_categories

  The `unicode` dependency is a development one; the generated module
  needs nothing at runtime.

  """

  use Mix.Task

  @output "lib/localize/number/lexer/categories.ex"

  # Each predicate the lexer calls, and the categories it covers.
  @predicates [
    format?: [:Cf],
    digit?: [:Nd],
    mark?: [:Po, :Pf],
    space?: [:Zs]
  ]

  @impl Mix.Task
  def run(_args) do
    Mix.Task.run("loadpaths")

    if Code.ensure_loaded?(Unicode.GeneralCategory) do
      write_module()
    else
      Mix.raise(
        "The unicode library is not available. Run this task in the :dev environment, " <>
          "where mix.exs lists it."
      )
    end
  end

  defp write_module do
    source =
      module_source()
      |> Code.format_string!()
      |> IO.iodata_to_binary()

    File.write!(@output, source <> "\n")

    Mix.shell().info(
      "Wrote #{@output} from unicode #{library_version()} (Unicode #{unicode_version()})"
    )
  end

  defp module_source do
    predicates = Enum.map_join(@predicates, "\n\n", &predicate_source/1)

    """
    # Generated by `mix localize.gen_unicode_categories` from unicode #{library_version()}
    # (Unicode #{unicode_version()}). Do not edit; rerun the task when the library updates.
    defmodule Localize.Number.Lexer.Categories do
      @moduledoc false

      # The Unicode general categories `Localize.Number.Lexer` classes a
      # character by once its lexicon has not: each predicate takes a
      # codepoint and is a guard over the category's ranges.

      @doc false
      @spec unicode_version() :: String.t()
      def unicode_version do
        #{inspect(unicode_version())}
      end

    #{predicates}
    end
    """
  end

  defp predicate_source({name, categories}) do
    ranges =
      categories
      |> Enum.flat_map(&Unicode.GeneralCategory.get/1)
      |> Enum.sort()

    guard = Enum.map_join(ranges, " or\n      ", &range_source/1)

    """
      @doc false
      @spec #{name}(non_neg_integer()) :: boolean()
      # A generated range table: one guard per category is the fastest lookup.
      # credo:disable-for-next-line Credo.Check.Refactor.CyclomaticComplexity
      def #{name}(codepoint)
          when #{guard} do
        true
      end

      def #{name}(_codepoint) do
        false
      end
    """
  end

  defp range_source({from, from}) do
    "codepoint == #{hex(from)}"
  end

  defp range_source({from, to}) do
    "codepoint in #{hex(from)}..#{hex(to)}"
  end

  defp hex(codepoint) do
    "0x" <> String.pad_leading(Integer.to_string(codepoint, 16), 4, "0")
  end

  defp unicode_version do
    Unicode.version()
    |> Tuple.to_list()
    |> Enum.join(".")
  end

  defp library_version do
    :unicode
    |> Application.spec(:vsn)
    |> to_string()
  end
end
